#!/usr/bin/env python3
"""Generate the slicer-style G-code fixtures used by test_regression.py.

The generated files are committed, and golden.json records marlin-calc's
results for them: after regenerating, re-run pytest with --update-golden.
"""

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

LAYER_HEIGHT = 0.2
LINE_WIDTH = 0.45
E_PER_MM = LAYER_HEIGHT * LINE_WIDTH / (math.pi * 1.75 ** 2 / 4)


def circle(cx, cy, r, segments=72):
    return [(cx + r * math.cos(2 * math.pi * i / segments),
             cy + r * math.sin(2 * math.pi * i / segments))
            for i in range(segments + 1)]


def square(cx, cy, half):
    return [(cx - half, cy - half), (cx + half, cy - half),
            (cx + half, cy + half), (cx - half, cy + half), (cx - half, cy - half)]


def serpentine(x0, y0, x1, y1, spacing, vertical, clip=None):
    """Connected infill lines across a box, optionally clipped to a circle."""
    points = []
    steps = int((x1 - x0 if vertical else y1 - y0) / spacing)
    for i in range(steps + 1):
        a = (x0 if vertical else y0) + i * spacing
        lo, hi = (y0, y1) if vertical else (x0, x1)
        if clip:
            cx, cy, r = clip
            offset = a - (cx if vertical else cy)
            if abs(offset) >= r:
                continue
            half = math.sqrt(r * r - offset * offset)
            center = cy if vertical else cx
            lo, hi = center - half, center + half
        ends = [lo, hi] if i % 2 == 0 else [hi, lo]
        points += [(a, b) if vertical else (b, a) for b in ends]
    return points


class Printer:
    def __init__(self, relative_e):
        self.lines = []
        self.relative_e = relative_e
        self.x = self.y = self.e = 0.0

    def __call__(self, line):
        self.lines.append(line)

    def travel(self, x, y, feedrate):
        self(f"G0 F{feedrate} X{x:.3f} Y{y:.3f}")
        self.x, self.y = x, y

    def extrude(self, points, feedrate, flow=1.0):
        """Travel-free extrusion along points, starting from the current position."""
        self(f"G1 F{feedrate}")
        for x, y in points:
            de = math.hypot(x - self.x, y - self.y) * E_PER_MM * flow
            self.e += de
            self(f"G1 X{x:.3f} Y{y:.3f} E{de if self.relative_e else self.e:.5f}")
            self.x, self.y = x, y

    def arc(self, command, x, y, i, j, length):
        self.e += length * E_PER_MM
        self(f"{command} X{x:.3f} Y{y:.3f} I{i:.3f} J{j:.3f} E{self.e:.5f}")
        self.x, self.y = x, y

    def reset_e(self):
        self("G92 E0")
        self.e = 0.0

    def save(self, name):
        with open(HERE / name, "w", newline="\n") as f:
            f.write("\n".join(self.lines) + "\n")


def prusaslicer_style():
    """Relative E, slicer retractions with Z hop, classic jerk, a cube and a cylinder."""
    p = Printer(relative_e=True)
    p("; Synthetic PrusaSlicer-style print, generated by make_fixtures.py")
    p("M201 X1000 Y1000 Z200 E5000 ; sets maximum accelerations, mm/sec^2")
    p("M203 X200 Y200 Z12 E120 ; sets maximum feedrates, mm / sec")
    p("M204 P1250 R1250 T1250 ; sets acceleration (P, T) and retract acceleration (R), mm/sec^2")
    p("M205 X8.00 Y8.00 Z0.40 E4.50 ; sets the jerk limits, mm/sec")
    p("M205 S0 T0 ; sets the minimum extruding and travel feed rate, mm/sec")
    p("M107")
    p("M104 S215 ; set temperature")
    p("M140 S60 ; set bed temperature")
    p("M190 S60 ; wait for bed temperature to be reached")
    p("M109 S215 ; wait for temperature to be reached")
    p("G28 ; home all axes")
    p("G1 Z5 F5000 ; lift nozzle")
    p("G21 ; set units to millimeters")
    p("G90 ; use absolute coordinates")
    p("M83 ; use relative distances for extrusion")
    p("G1 Z0.3 F720")
    p.travel(5, 10, 5000)
    p.extrude([(5, 120)], 1000, flow=2)
    p("G1 E-0.8 F2100")
    layers = 10
    for layer in range(layers):
        z = LAYER_HEIGHT * (layer + 1)
        solid = layer < 2 or layer >= layers - 2
        p(";LAYER_CHANGE")
        p(f";Z:{z:.1f}")
        if layer == 1:
            p("M106 S255")
        external_f, perimeter_f, infill_f = (1200, 1200, 1200) if layer == 0 else (1500, 2400, 4800)
        for loops, infill in [
            ([square(100, 100, 9.775), square(100, 100, 9.325)],
             (90.9, 90.9, 109.1, 109.1, None)),
            ([circle(140, 100, 7.775), circle(140, 100, 7.325)],
             (133, 93, 147, 107, (140, 100, 7.1))),
        ]:
            start = loops[0][0]
            p(f"G1 Z{z + 0.4:.1f} F720")
            p.travel(*start, 9000)
            p(f"G1 Z{z:.1f} F720")
            p("G1 E0.8 F2100")
            for loop in loops:
                if (p.x, p.y) != loop[0]:
                    p.travel(*loop[0], 9000)
                p.extrude(loop[1:], external_f if loop is loops[0] else perimeter_f)
            x0, y0, x1, y1, clip = infill
            fill = serpentine(x0, y0, x1, y1, LINE_WIDTH if solid else 2.0,
                              vertical=layer % 2 == 1, clip=clip)
            p.travel(*fill[0], 9000)
            p.extrude(fill[1:], infill_f)
            p("G1 E-0.8 F2100")
    p("M107")
    p(f"G1 Z{LAYER_HEIGHT * layers + 10:.1f} F720")
    p("G1 X0 Y200 F3000 ; present print")
    p("M104 S0 ; turn off temperature")
    p("M140 S0 ; turn off heatbed")
    p("M84 ; disable motors")
    p.save("prusaslicer_style.gcode")


def cura_arcwelder_style():
    """Absolute E, G2/G3 arcs, firmware retraction, junction deviation, linear advance."""
    p = Printer(relative_e=False)
    p(";FLAVOR:Marlin")
    p(";Synthetic Cura + ArcWelder-style print, generated by make_fixtures.py")
    p("M140 S60")
    p("M105")
    p("M190 S60")
    p("M104 S200")
    p("M105")
    p("M109 S200")
    p("M82 ;absolute extrusion mode")
    p("M207 S4 F2400 Z0.3")
    p("M208 F1800")
    p("M205 J0.02")
    p("M900 K0.08")
    p("G28 ;Home")
    p.reset_e()
    p("G1 Z2.0 F3000")
    p.travel(0.1, 20, 5000)
    p("G1 Z0.3")
    p.extrude([(0.1, 200)], 1500, flow=2)
    p.reset_e()
    p("G10")
    layers = 10
    p(f";LAYER_COUNT:{layers}")
    for layer in range(layers):
        z = LAYER_HEIGHT * (layer + 1)
        p(f";LAYER:{layer}")
        p.reset_e()
        wall_f, fill_f = (1200, 1200) if layer == 0 else (1500, 3600)

        # Rounded rectangle 40 x 20 with 5 mm corner radii, counter-clockwise.
        p.travel(85, 90, 7200)
        p(f"G0 Z{z:.1f}")
        p("G11")
        p("M204 S500")
        p(";TYPE:WALL-OUTER")
        quarter = math.pi * 5 / 2
        p.extrude([(115, 90)], wall_f)
        p.arc("G3", 120, 95, 0, 5, quarter)
        p.extrude([(120, 105)], wall_f)
        p.arc("G3", 115, 110, -5, 0, quarter)
        p.extrude([(85, 110)], wall_f)
        p.arc("G3", 80, 105, 0, -5, quarter)
        p.extrude([(80, 95)], wall_f)
        p.arc("G3", 85, 90, 5, 0, quarter)
        p("M204 S2000")
        p(";TYPE:FILL")
        fill = serpentine(82, 92, 118, 108, 2.0, vertical=layer % 2 == 1)
        p.travel(*fill[0], 7200)
        p.extrude(fill[1:], fill_f)
        p("G10")

        # Cylinder: concentric full circles, clockwise.
        p("M204 S3000")
        p.travel(140, 100, 7200)
        p("G11")
        p("M204 S500")
        p(";TYPE:WALL-OUTER")
        for r in (9.775, 9.325, 7.0, 5.0, 3.0):
            p.travel(150 - r, 100, 7200)
            p(f"G1 F{wall_f}")
            p.arc("G2", 150 - r, 100, r, 0, 2 * math.pi * r)
        p("G10")
    p(f"G0 Z{LAYER_HEIGHT * layers + 5:.1f}")
    p("M104 S0")
    p("M140 S0")
    p("M84")
    p.save("cura_arcwelder_style.gcode")


def dual_extruder():
    """Two tools with tool changes, per-tool flow, dwells, and a prime tower."""
    p = Printer(relative_e=False)
    p("; Synthetic dual-extruder print, generated by make_fixtures.py")
    p("M82")
    p("M104 T0 S210")
    p("M104 T1 S220")
    p("M140 S60")
    p("M190 S60")
    p("M109 T0 S210")
    p("M109 T1 S220")
    p("M221 T1 S95")
    p("G28")
    p("G1 Z0.2 F720")
    p("T0")
    p.reset_e()
    tool = 0
    layers = 8
    for layer in range(layers):
        z = LAYER_HEIGHT * (layer + 1)
        p(f";LAYER:{layer}")
        p(f"G1 Z{z:.1f} F720")
        for change in range(2):
            if layer or change:
                p(f"G1 E{p.e - 10:.5f} F3000")
                tool = 1 - tool
                p(f"T{tool}")
                p.reset_e()
                p("G4 S2")
                p.travel(170, 170, 9000)
                p("G1 E10 F3000")
                p.e = 10
                p.extrude(square(175, 175, 5)[1:], 1800)
            cx = 80 if tool == 0 else 120
            p.travel(cx - 9.775, 100 - 9.775, 9000)
            p.extrude(square(cx, 100, 9.775)[1:], 1800)
            p.travel(cx - 9.325, 100 - 9.325, 9000)
            p.extrude(square(cx, 100, 9.325)[1:], 2400)
            fill = serpentine(cx - 8.9, 91.1, cx + 8.9, 108.9, 2.0, vertical=layer % 2 == 1)
            p.travel(*fill[0], 9000)
            p.extrude(fill[1:], 4800)
    p(f"G1 Z{LAYER_HEIGHT * layers + 10:.1f} F720")
    p("M104 T0 S0")
    p("M104 T1 S0")
    p("M140 S0")
    p("M84")
    p.save("dual_extruder.gcode")


if __name__ == "__main__":
    prusaslicer_style()
    cura_arcwelder_style()
    dual_extruder()
