"""G-code syntax that marlin-calc must accept or ignore."""

import functools
import operator

import pytest

PROGRAM = (
    "G1 X10 Y10 F3000\n"
    "G1 X50 Y10 E2\n"
    "G1 X50 Y50 E4\n"
    "G1 X10 Y50 E6\n"
    "G1 X10 Y10 E8\n"
)


def summary(result):
    return result.time, result.filament(), len(result.progress)


def with_line_numbers(gcode: str) -> str:
    lines = []
    for number, line in enumerate(gcode.splitlines(), 1):
        command = f"N{number} {line}"
        checksum = functools.reduce(operator.xor, command.encode())
        lines.append(f"{command}*{checksum}\n")
    return "".join(lines)


@pytest.mark.parametrize("rewrite", [
    pytest.param(lambda g: g.replace("\n", " ; G1 X500 E100\n"), id="trailing-comments"),
    pytest.param(lambda g: "; generated by a slicer\n;LAYER:0\n" + g, id="comment-lines"),
    pytest.param(with_line_numbers, id="line-numbers-and-checksums"),
    pytest.param(lambda g: g.replace("\n", "\r\n"), id="crlf"),
    pytest.param(lambda g: g.replace("\n", "\n\n   \n"), id="blank-lines"),
    pytest.param(lambda g: g.replace("G1", "   G1"), id="leading-whitespace"),
    pytest.param(lambda g: g.replace(" ", "\t"), id="tabs"),
])
def test_equivalent_spellings(calc, rewrite):
    assert summary(calc(rewrite(PROGRAM))) == summary(calc(PROGRAM))


@pytest.mark.parametrize("command", [
    "M104 S200", "M109 S200", "M140 S60", "M190 S60", "M106 S255", "M107",
    "M117 Printing...", "M73 P50", "M300 S440 P200", "M84", "M105", "G21",
    "G29", "M420 S1", "M500",
])
def test_unsupported_commands_are_ignored(calc, command):
    lines = PROGRAM.splitlines(keepends=True)
    gcode = "".join(lines[:2]) + command + "\n" + "".join(lines[2:])
    assert summary(calc(gcode)) == summary(calc(PROGRAM))


def test_overlong_line_is_tolerated(calc):
    assert summary(calc("M117 " + "x" * 1000 + "\n" + PROGRAM)) == summary(calc(PROGRAM))


@pytest.mark.parametrize("gcode", ["", "\n\n", "; only a comment\n"])
def test_file_without_commands(calc, gcode):
    result = calc(gcode)
    assert result.time == 0
    assert result.progress == []
    assert result.analysis["filament"] == {}
